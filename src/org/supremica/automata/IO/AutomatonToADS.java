/******************* AutomatonToADS.java **********************
 * Conversion from Supremica format to PiTCT .ads format
 * Called from AutomataToADS
 */
package org.supremica.automata.IO;

import java.util.*;
import java.io.*;
import javax.swing.filechooser.FileFilter;

import org.supremica.automata.Arc;
import org.supremica.automata.Automaton;
import org.supremica.automata.State;
import org.supremica.automata.LabeledEvent;

import net.sourceforge.waters.model.marshaller.StandardExtensionFileFilter;

public class AutomatonToADS
	implements AutomataSerializer
{
	public static StandardExtensionFileFilter getFileFilter()
	{
		return new StandardExtensionFileFilter("PiTCT files (*.ads)", ".ads");
	}

	// PiTCT assumes that the (single!) initial state has index 0
	// So we create a map that guarantees that this is the case
	private final Map<State, Integer> stateMap;

	// PiTCT has controllable events as odd integers, and uncontrollable events as even
	// In addition, when converting a set of Supremica automata we need to guarantee
	// that same-labeled events correspond to the same integer in all automata
	// So, the event map is passed to us from AutomataToADS
	private Map<String, Integer> eventMap;

	private final Automaton aut;

	public AutomatonToADS(final Automaton aut, final Map<String, Integer> unionMap)
	{
		this.aut = aut;
		this.eventMap = unionMap;
		this.stateMap = buildStateMap();
	}

	@Override
	public void serialize(final PrintWriter pw)
		throws Exception
	{
		pw.println(aut.getName()); // PiTCT .ads start with the name on first line
		pw.println();
		pw.println("State size (State set will be (0,1....,size-1)):");
		pw.println(aut.nbrOfStates());
		pw.println();
		pw.println("Marker states:");

		printMarkedStates(pw);

		pw.println("\n\nVocal states:\n"); // No idea what this is but it is there

		pw.println("Transitions:");
		printTransitions(pw);

		pw.println("# Generated by Supremica " + java.time.LocalDateTime.now().truncatedTo(java.time.temporal.ChronoUnit.MINUTES));

	}

	@Override
	public void serialize(final String fileName)
		throws Exception
	{
		final PrintWriter pw = new PrintWriter(new FileWriter(fileName));
		serialize(pw);
		pw.flush();
		pw.close();
	}

	///////////////////////////////// Private parts below

	private void printMarkedStates(final PrintWriter pw)
	{
		// Find the marked (accepting) states and write their indices
		final Iterator<State> states_it = aut.stateIterator();
		while (states_it.hasNext())
		{
			State state = (State) states_it.next();
			if (state.isAccepting())
			{
				pw.print(stateMap.get(state));
				pw.print(" ");
			}
		}
	}

	// This is a bit ugly, but we must guarantee that the (single!) initial state
	// is numbered 0 and the other states are numbered consecutively 1..num_states-1
	private Map<State, Integer> buildStateMap()
	{
		final Map<State, Integer> stateMap = new HashMap<>();
		final State initState = aut.getInitialState();
		stateMap.put(initState, 0);
		int countStates = 1;

		final Iterator<State> states_it = aut.stateIterator();
		while (states_it.hasNext())
		{
			final State state = states_it.next();
			if(state != initState)
				stateMap.put(state, countStates++);
		}

		return stateMap;
	}

	private void printTransitions(final PrintWriter pw)
	{
		final Iterator<State> states = aut.stateIterator();
		while (states.hasNext())
		{
			final State sourceState = states.next();
			final int srcInt = stateMap.get(sourceState);
			final Iterator<Arc> outgoingArcs = sourceState.outgoingArcsIterator();
			while (outgoingArcs.hasNext())
			{
				final Arc arc = (Arc) outgoingArcs.next();
				final State destState = arc.getToState();
				final LabeledEvent event = arc.getEvent();
				final StringBuffer buf = new StringBuffer();
				buf.append(srcInt);
				buf.append(" ");
				buf.append(eventMap.get(event.getLabel()));
				buf.append(" ");
				buf.append(stateMap.get(destState));
				pw.println(buf.toString());
			}
		}
	}

	private String sanityCheck()
	{
		if (!aut.hasInitialState())
		{
			return "This automaton has no initial state";
		}
		return null;
	}
}